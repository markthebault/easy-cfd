// Capture real, exploratory WebGPU runs; the course never invents CFD output.
import { chromium } from '@playwright/test';
import { createServer } from 'vite';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const here=dirname(fileURLToPath(import.meta.url)), root=resolve(here,'..');
const manifest=JSON.parse(readFileSync(resolve(root,'public/course/models/manifest.json'),'utf8'));
const server=await createServer({root,server:{host:'127.0.0.1',port:5297,strictPort:true,hmr:false},logLevel:'error'});
let browser;
const output={capturedAt:new Date().toISOString(),commit:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),qualification:'exploratory; no experimental validation or mesh-independence claim',settings:{speed_kmh:100,yaw_deg:0,quality:'custom',custom_cells:72,custom_passes:10,reference_area:2.2,density:1.225,moving_ground:true,wheels:true,detail_ratio:1},geometry:'Original synthetic teaching car, generated by course/make-models.mjs',geometryFiles:manifest.files.map(({file,sha256,triangles,closedMesh})=>({file,sha256,triangles,closedMesh})),cases:[]};
try {
  await server.listen();
  browser=await chromium.launch({headless:true,args:['--enable-unsafe-webgpu','--enable-gpu','--ignore-gpu-blocklist',...(process.platform==='darwin'?['--use-angle=metal']:[])]});
  const page=await browser.newPage();
  await page.goto('http://127.0.0.1:5297/bench.html');
  await page.waitForFunction(()=>window.cfdBench?.ready);
  const variants=[['baseline',[]],['wing6',['rear_wing_6.stl']],['wing12',['rear_wing_12.stl']],['splitter',['front_splitter.stl']],['canards',['canard_pair.stl']],['diffuser7',['body_diffuser_7.stl']],['diffuser14',['body_diffuser_14.stl']],['diffuser7skirts',['body_diffuser_7.stl','side_skirts.stl']],['package',['body_diffuser_7.stl','rear_wing_6.stl','front_splitter.stl','canard_pair.stl','side_skirts.stl']]];
  for(const [id,enabled] of variants) {
    const parts=manifest.files.map(f=>({url:`/course/models/${f.file}`,name:f.name,role:f.role,wheel:f.wheel??null,active:f.role==='wheel'||(f.file==='body_flat.stl'&&!enabled.some(v=>v.startsWith('body_diffuser')))||enabled.includes(f.file)}));
    console.log(`Running ${id}...`);
    try {
      const result=await page.evaluate(spec=>window.cfdBench.run(spec),{parts,settings:output.settings});
      output.cases.push({id,enabled,result});
      console.log(`${id}: Cd=${result.cd.toFixed(4)} Cl=${result.cl.toFixed(4)}, ${result.cells} cells, settled=${result.settled}, ${result.wallSeconds.toFixed(0)} s`);
    } catch(error) { output.cases.push({id,enabled,error:String(error)}); console.log(`${id}: FAILED ${error}`); }
    writeFileSync(resolve(here,'evidence/runs.in-progress.json'),JSON.stringify(output,null,2)+'\n');
  }
} finally {await browser?.close();await server.close();}
if(output.cases.some(c=>c.error))process.exitCode=1;
else writeFileSync(resolve(here,'evidence/runs.json'),JSON.stringify(output,null,2)+'\n');
